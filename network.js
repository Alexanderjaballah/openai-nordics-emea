export function accountPotential(a,p=networkCases.ambition){
 const users=Math.min(a.people,Math.round(a.people*a.eligibleShare*p.workforce/100));
 const workforce=users*p.monthly*12;
 const tasks=a.tasksM*1e6*p.volume/100;
 const api=tasks*p.taskCost;
 return {users,workforce,tasks,api,total:workforce+api};
}
export function portfolioPotential(p=networkCases.ambition,includeReview=true){
 return network.filter(a=>includeReview||a.relationship!=='review').reduce((s,a)=>{const r=accountPotential(a,p);for(const k of Object.keys(r))s[k]+=r[k];return s},{users:0,workforce:0,tasks:0,api:0,total:0});
}
